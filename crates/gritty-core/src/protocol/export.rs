//! Generates `packages/protocol/src/generated/*.ts` from the Rust protocol types.
//!
//! Run with `cargo test -p gritty-core`. CI fails when the committed output is
//! stale (`pnpm check:generated`). Add every new protocol root type to
//! `export_bindings`; dependencies are exported transitively.

use std::fs;
use std::path::Path;

use ts_rs::{Config, TS};

use super::{CORE_EVENT_CHANNEL, PROTOCOL_VERSION};
use crate::document::{
    CloseDocumentRequest, DocumentContent, DocumentStatusRequest, OpenDocumentRequest,
    ReloadDocumentRequest, SaveDocumentRequest, UpdateDocumentRequest,
};
use crate::event::{CoreEvent, EventMeta};
use crate::health::HealthReport;
use crate::operation::Operation;
use crate::operation::demo::StartDemoRequest;
use crate::operation::registry::CancelOperationRequest;
use crate::protocol::error::CoreError;
use crate::workspace::{
    CloseWorkspaceRequest, ListDirectoryRequest, ListDirectoryResponse, OpenWorkspaceRequest,
    Workspace,
};

/// Relative to this crate's `Cargo.toml`.
const GENERATED_DIR: &str = "../../packages/protocol/src/generated";

const HEADER: &str =
    "// Generated by `cargo test -p gritty-core` from crates/gritty-core; do not edit.\n";

#[test]
fn export_bindings() {
    let out = Path::new(env!("CARGO_MANIFEST_DIR")).join(GENERATED_DIR);
    fs::create_dir_all(&out).expect("create generated dir");
    // Remove previous output so renamed or deleted types do not linger.
    for entry in fs::read_dir(&out).expect("read generated dir") {
        let path = entry.expect("dir entry").path();
        if path.extension().is_some_and(|ext| ext == "ts") {
            fs::remove_file(&path).expect("remove stale binding");
        }
    }

    let cfg = Config::new().with_out_dir(&out).with_large_int("number");
    HealthReport::export_all(&cfg).expect("export HealthReport");
    CoreError::export_all(&cfg).expect("export CoreError");
    Operation::export_all(&cfg).expect("export Operation");
    CoreEvent::export_all(&cfg).expect("export CoreEvent");
    EventMeta::export_all(&cfg).expect("export EventMeta");
    CancelOperationRequest::export_all(&cfg).expect("export CancelOperationRequest");
    StartDemoRequest::export_all(&cfg).expect("export StartDemoRequest");
    Workspace::export_all(&cfg).expect("export Workspace");
    OpenWorkspaceRequest::export_all(&cfg).expect("export OpenWorkspaceRequest");
    CloseWorkspaceRequest::export_all(&cfg).expect("export CloseWorkspaceRequest");
    ListDirectoryRequest::export_all(&cfg).expect("export ListDirectoryRequest");
    ListDirectoryResponse::export_all(&cfg).expect("export ListDirectoryResponse");
    DocumentContent::export_all(&cfg).expect("export DocumentContent");
    OpenDocumentRequest::export_all(&cfg).expect("export OpenDocumentRequest");
    CloseDocumentRequest::export_all(&cfg).expect("export CloseDocumentRequest");
    UpdateDocumentRequest::export_all(&cfg).expect("export UpdateDocumentRequest");
    SaveDocumentRequest::export_all(&cfg).expect("export SaveDocumentRequest");
    ReloadDocumentRequest::export_all(&cfg).expect("export ReloadDocumentRequest");
    DocumentStatusRequest::export_all(&cfg).expect("export DocumentStatusRequest");

    let version = format!(
        "{HEADER}export const PROTOCOL_VERSION = \"{PROTOCOL_VERSION}\";\n\
         export const CORE_EVENT_CHANNEL = \"{CORE_EVENT_CHANNEL}\";\n"
    );
    fs::write(out.join("version.ts"), version).expect("write version.ts");
}
